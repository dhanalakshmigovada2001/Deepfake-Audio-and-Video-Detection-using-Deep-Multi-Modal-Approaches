def predict_from_file(model_path, npy_path):
    import torch
    import numpy as np
    from torchvision.models import vit_b_32, ViT_B_32_Weights
    import os

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Load model
    weights = ViT_B_32_Weights.DEFAULT
    model = vit_b_32(weights=weights)
    model.heads.head = torch.nn.Linear(model.heads.head.in_features, 2)
    model.load_state_dict(torch.load(model_path, map_location=device))
    model = model.to(device)
    model.eval()

    # Load and preprocess MFCC
    mfcc = np.load(npy_path)
    mfcc = (mfcc - np.mean(mfcc)) / (np.std(mfcc) + 1e-9)
    mfcc = np.expand_dims(mfcc, axis=0)     # (1, H, W)
    mfcc = np.repeat(mfcc, 3, axis=0)       # (3, H, W)
    tensor = torch.tensor(mfcc, dtype=torch.float32).unsqueeze(0).to(device)  # (1, 3, H, W)

    # Predict
    with torch.no_grad():
        output = model(tensor)
        prediction = torch.argmax(output, dim=1).item()

    return prediction, output.softmax(dim=1).squeeze().tolist()

