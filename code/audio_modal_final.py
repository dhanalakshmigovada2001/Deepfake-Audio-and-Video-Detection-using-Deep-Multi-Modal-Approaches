class MFCCDataset(Dataset):
    """
    Custom Dataset for MFCC features compatible with Vision Transformer
    Handles variable-length MFCC sequences and converts them to fixed-size images
    """

    def __init__(self, mfcc_dir, target_size=224, max_length=500):
        self.files = glob(f"{mfcc_dir}/*.npy")
        self.labels = [0 if 'bonafide' in f else 1 for f in self.files]
        self.target_size = target_size
        self.max_length = max_length

        print(f"Dataset initialized with {len(self.files)} files")
        print(f"Bonafide samples: {self.labels.count(0)}")
        print(f"Spoof samples: {self.labels.count(1)}")

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        # Load MFCC data
        path = self.files[idx]
        data = np.load(path)  # Shape: (n_mfcc, time_frames)
        label = self.labels[idx]

        # Normalize the data
        data = (data - np.mean(data)) / (np.std(data) + 1e-9)

        # Handle variable time length
        n_mfcc, time_frames = data.shape

        # Pad or truncate to max_length
        if time_frames < self.max_length:
            # Pad with zeros
            pad_width = self.max_length - time_frames
            data = np.pad(data, ((0, 0), (0, pad_width)), mode='constant', constant_values=0)
        elif time_frames > self.max_length:
            # Truncate to max_length
            data = data[:, :self.max_length]

        # Now data shape is (n_mfcc, max_length)
        # Convert to tensor and add channel dimension
        data_tensor = torch.tensor(data, dtype=torch.float32).unsqueeze(0)  # (1, n_mfcc, max_length)

        # Resize to target_size x target_size for ViT
        data_resized = TF.resize(data_tensor, (self.target_size, self.target_size), antialias=True)

        # Repeat to create 3 channels (RGB-like) for ViT: (1, 224, 224) -> (3, 224, 224)
        data_final = data_resized.repeat(3, 1, 1)

        return data_final, torch.tensor(label, dtype=torch.long)

