def evaluate_model(model, data_loader, dataset_name="Test"):
    """Comprehensive model evaluation"""
    model.eval()
    all_preds = []
    all_labels = []
    all_probs = []

    print(f"🔍 Evaluating model on {dataset_name} set...")

    with torch.no_grad():
        for data, target in tqdm(data_loader, desc=f"Evaluating {dataset_name}"):
            data = data.to(device)
            output = model(data)

            # Get probabilities and predictions
