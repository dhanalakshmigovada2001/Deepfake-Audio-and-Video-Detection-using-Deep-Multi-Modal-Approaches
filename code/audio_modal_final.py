def train_model(model, train_loader, dev_loader, epochs=10, lr=1e-4, patience=3):
    """
    Train the Vision Transformer model with improved error handling
    """

    # Loss function and optimizer
    criterion = nn.CrossEntropyLoss()
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=0.01)

    # Learning rate scheduler
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode='min', factor=0.5, patience=2, verbose=True
    )

    # Training history
    history = {
        "train_loss": [], "train_acc": [],
        "val_loss": [], "val_acc": []
    }

    best_val_acc = 0.0
    patience_counter = 0

    print(f"🚀 Starting training for {epochs} epochs...")
    print(f"Training samples: {len(train_loader.dataset)}")
    print(f"Validation samples: {len(dev_loader.dataset)}")
    print(f"Batch size: {train_loader.batch_size}")
    print(f"Steps per epoch: {len(train_loader)}")

    for epoch in range(epochs):
        print(f"\n{'='*60}")
        print(f"EPOCH {epoch+1}/{epochs}")
        print(f"{'='*60}")

        start_time = time.time()

        # ============ TRAINING PHASE ============
        model.train()
        train_loss = 0.0
        train_correct = 0
        train_total = 0

        train_pbar = tqdm(train_loader, desc=f"Training Epoch {epoch+1}")
        for batch_idx, (data, target) in enumerate(train_pbar):
            try:
                data, target = data.to(device, non_blocking=True), target.to(device, non_blocking=True)

                # Zero gradients
                optimizer.zero_grad()

                # Forward pass
                output = model(data)
                loss = criterion(output, target)

                # Backward pass
                loss.backward()

                # Gradient clipping for stability
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)

                optimizer.step()

                # Statistics
                train_loss += loss.item()
                _, predicted = torch.max(output.data, 1)
                train_total += target.size(0)
                train_correct += (predicted == target).sum().item()

                # Update progress bar
                current_acc = 100. * train_correct / train_total
                train_pbar.set_postfix({
                    'Loss': f'{loss.item():.4f}',
                    'Acc': f'{current_acc:.2f}%'
                })

                # Memory cleanup every 50 batches
                if batch_idx % 50 == 0:
                    torch.cuda.empty_cache()

            except RuntimeError as e:
                if "out of memory" in str(e):
                    print(f"🚨 GPU out of memory at batch {batch_idx}. Clearing cache...")
                    torch.cuda.empty_cache()
                    gc.collect()
                    continue
                else:
                    raise e

        # Calculate training metrics
        epoch_train_loss = train_loss / len(train_loader)
        epoch_train_acc = 100. * train_correct / train_total

        # ============ VALIDATION PHASE ============
        model.eval()
        val_loss = 0.0
        val_correct = 0
        val_total = 0

        with torch.no_grad():
            val_pbar = tqdm(dev_loader, desc=f"Validation Epoch {epoch+1}")
            for data, target in val_pbar:
                try:
                    data, target = data.to(device, non_blocking=True), target.to(device, non_blocking=True)

                    output = model(data)
                    loss = criterion(output, target)

                    val_loss += loss.item()
                    _, predicted = torch.max(output.data, 1)
                    val_total += target.size(0)
                    val_correct += (predicted == target).sum().item()

                    # Update progress bar
                    current_acc = 100. * val_correct / val_total
                    val_pbar.set_postfix({
                        'Loss': f'{loss.item():.4f}',
                        'Acc': f'{current_acc:.2f}%'
                    })

                except RuntimeError as e:
                    if "out of memory" in str(e):
                        print(f"🚨 GPU out of memory during validation. Clearing cache...")
                        torch.cuda.empty_cache()
                        gc.collect()
                        continue
                    else:
                        raise e

        # Calculate validation metrics
        epoch_val_loss = val_loss / len(dev_loader)
        epoch_val_acc = 100. * val_correct / val_total

        # Update learning rate scheduler
        scheduler.step(epoch_val_loss)

        # Save metrics
        history["train_loss"].append(epoch_train_loss)
        history["train_acc"].append(epoch_train_acc)
        history["val_loss"].append(epoch_val_loss)
        history["val_acc"].append(epoch_val_acc)

        # Print epoch summary33
        epoch_time = time.time() - start_time
        print(f"\nEPOCH {epoch+1} SUMMARY:")
        print(f"Train Loss: {epoch_train_loss:.4f} | Train Acc: {epoch_train_acc:.2f}%")
        print(f"Val Loss: {epoch_val_loss:.4f} | Val Acc: {epoch_val_acc:.2f}%")
        print(f"Time: {epoch_time:.2f}s")
        print(f"Learning Rate: {optimizer.param_groups[0]['lr']:.2e}")

        # Print system stats
        try:
            print_system_stats()
        except Exception as e:
            print(f"System stats error: {e}")

        # Early stopping and model saving
        if epoch_val_acc > best_val_acc:
            best_val_acc = epoch_val_acc
            patience_counter = 0
            # Save best model
            model_save_path = f"/kaggle/working/best_{SELECTED_MODEL}_mfcc_model.pth"
            torch.save(model.state_dict(), model_save_path)
            print(f"🎯 New best validation accuracy: {best_val_acc:.2f}% - Model saved!")
        else:
            patience_counter += 1
            print(f"Patience: {patience_counter}/{patience}")

        # Early stopping
        if patience_counter >= patience:
            print(f"🛑 Early stopping triggered after {epoch+1} epochs")
            break

        # Memory cleanup
        torch.cuda.empty_cache()
        gc.collect()

    print(f"\n🏁 Training completed!")
    print(f"Best validation accuracy: {best_val_acc:.2f}%")

    return history

